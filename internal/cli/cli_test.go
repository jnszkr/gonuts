func shopPath(t *testing.T) string {
	t.Helper()
	p, err := filepath.Abs(filepath.Join("..", "..", "examples", "shop", "nuts.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	return p
}

func run(args ...string) (code int, stdout, stderr string) {
	var out, errb bytes.Buffer
	code = Run(args, &out, &errb)
	return code, out.String(), errb.String()
}

func listFiles(t *testing.T, dir string) []string {
	t.Helper()
	var out []string
	err := filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			rel, _ := filepath.Rel(dir, p)
			out = append(out, rel)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func genArgs(t *testing.T, dir string, extra ...string) []string {
	t.Helper()
	return append([]string{"generate", "--spec", shopPath(t), "--out", dir, "--import-path", "x.com/gen"}, extra...)
}

func TestGenerateDefaultsToAllGoAndNoTerraform(t *testing.T) {
	dir := t.TempDir()
	tf := filepath.Join(dir, "infra")
	code, out, errOut := run(genArgs(t, filepath.Join(dir, "gen"), "--terraform-out", tf)...)
	if code != 0 {
		t.Fatalf("code %d: %s", code, errOut)
	}
	files := listFiles(t, filepath.Join(dir, "gen"))
	if len(files) != 8 {
		t.Errorf("files = %v", files)
	}
	if _, err := os.Stat(tf); !os.IsNotExist(err) {
		t.Errorf("terraform was generated by default")
	}
	if !strings.Contains(out, "8 files") {
		t.Errorf("stdout = %q", out)
	}
}

func TestGenerateFlagsNarrowOutput(t *testing.T) {
	for flag, want := range map[string]string{
		"--models":    "models/models.go",
		"--pubsub":    "events/events.go",
		"--consumers": "consumers/consumers.go",
		"--kv":        "kv/kv.go",
		"--schedules": "schedules/schedules.go",
		"--rr-client": "client/orders/client.go",
		"--rr-server": "server/orders/server.go",
	} {
		t.Run(flag, func(t *testing.T) {
			dir := t.TempDir()
			if code, _, errOut := run(genArgs(t, dir, flag)...); code != 0 {
				t.Fatalf("code %d: %s", code, errOut)
			}
			files := strings.Join(listFiles(t, dir), " ")
			if !strings.Contains(files, want) {
				t.Errorf("%s not in %s", want, files)
			}
			for _, other := range []string{"kv/kv.go", "server/orders/server.go"} {
				if other != want && strings.Contains(files, other) {
					t.Errorf("unexpected %s", other)
				}
			}
		})
	}
}

