func TestSchedulesSyncPublishesToTheServer(t *testing.T) {
	url := natstest.Start(t)
	data, err := os.ReadFile(shopPath(t))
	if err != nil {
		t.Fatal(err)
	}
	s, err := spec.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	rt, err := nuts.Dial(url)
	if err != nil {
		t.Fatal(err)
	}
	defer rt.Close()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err := devnats.Provision(ctx, rt.JetStream(), s.Infra()); err != nil {
		t.Fatal(err)
	}
	code, out, errOut := run("schedules", "sync", "--spec", shopPath(t), "--server", url)
	if code != 0 || !strings.Contains(out, "1 schedule") {
		t.Fatalf("code %d: %s %s", code, out, errOut)
	}
	st, err := rt.JetStream().Stream(ctx, "CARTS")
	if err != nil {
		t.Fatal(err)
	}
	msg, err := st.GetLastMsgForSubject(ctx, "carts.schedules.sweep")
	if err != nil {
		t.Fatal(err)
	}
	if string(msg.Data) != `{"older_than":"24h"}` || msg.Header.Get(jetstream.MsgRollup) != "sub" || msg.Header.Get("Nats-Schedule-Target") != "carts.sweep" {
		t.Fatalf("message = %+v", msg)
	}
}

