func TestValidateJSONIsMachineReadable(t *testing.T) {
	code, out, _ := run("validate", "--json", "--spec", badSpec(t))
	var got struct {
		Valid  bool `json:"valid"`
		Errors []struct {
			Path    string `json:"path"`
			Message string `json:"message"`
		} `json:"errors"`
	}
	if err := json.Unmarshal([]byte(out), &got); err != nil {
		t.Fatalf("bad JSON %q: %v", out, err)
	}
	if code != 1 || got.Valid || got.Errors[0].Path != "name" {
		t.Fatalf("code %d, got %+v", code, got)
	}
	code, out, _ = run("validate", "--json", "--spec", shopPath(t))
	if err := json.Unmarshal([]byte(out), &got); err != nil {
		t.Fatal(err)
	}
	if code != 0 || !got.Valid {
		t.Fatalf("code %d, got %+v", code, got)
	}
}

