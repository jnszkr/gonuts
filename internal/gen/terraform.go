package gen

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/jnszkr/gonuts/internal/spec"
)

// block writes HCL formatted as `terraform fmt` would, aligning the = signs of
// consecutive attributes.
type block struct {
	header string
	attrs  [][2]string
	nested []*block
}

func (b *block) set(name, value string) { b.attrs = append(b.attrs, [2]string{name, value}) }

func (b *block) str(name, v string) {
	if v != "" {
		b.set(name, strconv.Quote(v))
	}
}

func (b *block) flag(name string, v bool) {
	if v {
		b.set(name, "true")
	}
}

func (b *block) list(name string, v []string) {
	if len(v) == 0 {
		return
	}
	quoted := make([]string, len(v))
	for i, s := range v {
		quoted[i] = strconv.Quote(s)
	}
	b.set(name, "["+strings.Join(quoted, ", ")+"]")
}

func num[N int | int32 | int64 | uint8 | uint64](b *block, name string, v N) {
	if v != 0 {
		b.set(name, fmt.Sprint(v))
	}
}

func seconds(d time.Duration) string {
	return strconv.FormatFloat(d.Seconds(), 'f', -1, 64)
}

func (b *block) seconds(name string, d spec.Duration) {
	if d.Duration != 0 {
		b.set(name, seconds(d.Duration))
	}
}

func (b *block) metadata(m map[string]string) {
	if len(m) == 0 {
		return
	}
	var parts []string
	for _, k := range spec.SortedKeys(m) {
		parts = append(parts, fmt.Sprintf("%s = %s", k, strconv.Quote(m[k])))
	}
	b.set("metadata", "{ "+strings.Join(parts, ", ")+" }")
}

func (b *block) render(out *strings.Builder, indent string) {
	out.WriteString(indent + b.header + " {\n")
	inner := indent + "  "
	width := 0
	for _, a := range b.attrs {
		width = max(width, len(a[0]))
	}
	for _, a := range b.attrs {
		fmt.Fprintf(out, "%s%-*s = %s\n", inner, width, a[0], a[1])
	}
	for i, n := range b.nested {
		if i > 0 || len(b.attrs) > 0 {
			out.WriteString("\n")
		}
		n.render(out, inner)
	}
	out.WriteString(indent + "}\n")
}

func renderBlocks(blocks []*block) []byte {
	var out strings.Builder
	out.WriteString("# Code generated by gonuts. DO NOT EDIT.\n\n")
	for i, b := range blocks {
		if i > 0 {
			out.WriteString("\n")
		}
		b.render(&out, "")
	}
	return []byte(out.String())
}

func tfName(s string) string {
	return strings.ToLower(strings.NewReplacer("-", "_", ".", "_").Replace(s))
}

// Terraform generates files for the NATS JetStream provider. It stops with an
// error when a setting has no provider equivalent, rather than dropping it.
func Terraform(s *spec.Spec) (map[string][]byte, error) {
	var unsupported []string
	files := map[string][]byte{"versions.tf": versionsTF(), "variables.tf": variablesTF()}

	var streams, consumers, buckets []*block
	for _, name := range spec.SortedKeys(s.Streams) {
		if s.Streams[name].Sealed {
			unsupported = append(unsupported, "streams."+name+".sealed")
		}
		streams = append(streams, streamBlock(s, name))
	}
	for _, name := range spec.SortedKeys(s.Consumers) {
		if s.Consumers[name].PauseUntil != nil {
			unsupported = append(unsupported, "consumers."+name+".pause_until")
		}
		consumers = append(consumers, consumerBlock(s, name))
	}
	for _, name := range spec.SortedKeys(s.KV) {
		unsupported = append(unsupported, unsupportedBucket(name, s.KV[name])...)
		buckets = append(buckets, bucketBlock(name, s.KV[name]))
	}
	if len(unsupported) > 0 {
		sort.Strings(unsupported)
		return nil, fmt.Errorf("the Terraform provider has no equivalent for: %s", strings.Join(unsupported, ", "))
	}
	for name, blocks := range map[string][]*block{"streams.tf": streams, "consumers.tf": consumers, "kv.tf": buckets} {
		if len(blocks) > 0 {
			files[name] = renderBlocks(blocks)
		}
	}
	return files, nil
}

func unsupportedBucket(name string, k spec.KVBucket) []string {
	var out []string
	if k.Placement != nil && k.Placement.Preferred != "" {
		out = append(out, "kv."+name+".placement.preferred")
	}
	if k.RePublish != nil {
		out = append(out, "kv."+name+".republish")
	}
	if k.Mirror != nil {
		out = append(out, "kv."+name+".mirror")
	}
	if len(k.Sources) > 0 {
		out = append(out, "kv."+name+".sources")
	}
	if k.Compression {
		out = append(out, "kv."+name+".compression")
	}
	if len(k.Metadata) > 0 {
		out = append(out, "kv."+name+".metadata")
	}
	return out
}

func versionsTF() []byte {
	required := &block{header: "required_providers"}
	required.set("jetstream", "{\n      source = \"nats-io/jetstream\"\n    }")
	tf := &block{header: "terraform", nested: []*block{required}}
	provider := &block{header: `provider "jetstream"`}
	provider.set("servers", "var.nats_servers")
	provider.set("credentials", "var.nats_credentials")
	return renderBlocks([]*block{tf, provider})
}

func variablesTF() []byte {
	servers := &block{header: `variable "nats_servers"`}
	servers.set("type", "string")
	servers.set("description", strconv.Quote("Comma-separated NATS server URLs."))
	creds := &block{header: `variable "nats_credentials"`}
	creds.set("type", "string")
	creds.set("description", strconv.Quote("Path to a NATS credentials file."))
	creds.set("default", "null")
	creds.set("sensitive", "true")
	return renderBlocks([]*block{servers, creds})
}

func streamBlock(s *spec.Spec, name string) *block {
	x := s.Streams[name]
	b := &block{header: fmt.Sprintf(`resource "jetstream_stream" %q`, tfName(name))}
	b.str("name", name)
	b.str("description", x.Description)
	b.list("subjects", s.StreamSubjects(name))
	b.str("retention", x.Retention)
	b.str("storage", x.Storage)
	b.str("discard", x.Discard)
	b.str("compression", x.Compression)
	b.str("persist_mode", x.PersistMode)
	num(b, "replicas", x.Replicas)
	num(b, "max_consumers", x.MaxConsumers)
	num(b, "max_msgs", x.MaxMsgs)
	num(b, "max_bytes", x.MaxBytes)
	num(b, "max_msgs_per_subject", x.MaxMsgsPerSubject)
	num(b, "max_msg_size", x.MaxMsgSize)
	num(b, "first_seq", x.FirstSeq)
	b.seconds("max_age", x.MaxAge)
	b.seconds("duplicate_window", x.Duplicates)
	b.seconds("subject_delete_marker_ttl", x.SubjectDeleteMarkerTTL)
	if x.NoAck {
		b.set("ack", "false")
	}
	b.flag("discard_new_per_subject", x.DiscardNewPerSubject)
	b.flag("deny_delete", x.DenyDelete)
	b.flag("deny_purge", x.DenyPurge)
	b.flag("allow_rollup_hdrs", x.AllowRollup || x.AllowMsgSchedules)
	b.flag("allow_direct", x.AllowDirect)
	b.flag("mirror_direct", x.MirrorDirect)
	b.flag("allow_msg_ttl", x.AllowMsgTTL)
	b.flag("allow_msg_counter", x.AllowMsgCounter)
	b.flag("allow_atomic", x.AllowAtomic)
	b.flag("allow_msg_schedules", x.AllowMsgSchedules)
	b.flag("allow_batched", x.AllowBatched)
	if p := x.Placement; p != nil {
		b.str("placement_cluster", p.Cluster)
		b.list("placement_tags", p.Tags)
		b.str("placement_preferred", p.Preferred)
	}
	if r := x.RePublish; r != nil {
		b.str("republish_source", r.Source)
		b.str("republish_destination", r.Destination)
		b.flag("republish_headers_only", r.HeadersOnly)
	}
	if l := x.ConsumerLimits; l != nil {
		b.seconds("inactive_threshold", l.InactiveThreshold)
		num(b, "max_ack_pending", l.MaxAckPending)
	}
	b.metadata(x.Metadata)
	if t := x.SubjectTransform; t != nil {
		nested := &block{header: "subject_transform"}
		nested.str("source", t.Source)
		nested.str("destination", t.Destination)
		b.nested = append(b.nested, nested)
	}
	if x.Mirror != nil {
		b.nested = append(b.nested, sourceBlock("mirror", *x.Mirror))
	}
	for _, src := range x.Sources {
		b.nested = append(b.nested, sourceBlock("source", src))
	}
	return b
}

func sourceBlock(header string, x spec.StreamSource) *block {
	b := &block{header: header}
	b.str("name", x.Name)
	b.str("filter_subject", x.FilterSubject)
	num(b, "start_seq", x.StartSeq)
	if x.StartTime != nil {
		b.str("start_time", x.StartTime.UTC().Format(time.RFC3339))
	}
	return b
}

var deliverAttrs = map[string]string{
	"": "deliver_all", "all": "deliver_all", "last": "deliver_last", "new": "deliver_new", "last_per_subject": "deliver_last_per_subject",
}

func consumerBlock(s *spec.Spec, name string) *block {
	c := s.Consumers[name]
	b := &block{header: fmt.Sprintf(`resource "jetstream_consumer" %q`, tfName(name))}
	b.set("stream_id", "jetstream_stream."+tfName(c.Stream)+".id")
	b.str("durable_name", name)
	b.str("description", c.Description)
	if filters := s.ConsumerFilters(name); len(filters) == 1 {
		b.str("filter_subject", filters[0])
	} else {
		b.list("filter_subjects", filters)
	}
	if attr, ok := deliverAttrs[c.DeliverPolicy]; ok {
		b.set(attr, "true")
	}
	num(b, "stream_sequence", c.OptStartSeq)
	if c.OptStartTime != nil {
		b.str("start_time", c.OptStartTime.UTC().Format(time.RFC3339))
	}
	b.str("ack_policy", c.AckPolicy)
	b.seconds("ack_wait", c.AckWait)
	num(b, "max_delivery", c.MaxDeliver)
	if len(c.BackOff) > 0 {
		parts := make([]string, len(c.BackOff))
		for i, d := range c.BackOff {
			parts[i] = seconds(d.Duration)
		}
		b.set("backoff", "["+strings.Join(parts, ", ")+"]")
	}
	b.str("replay_policy", c.ReplayPolicy)
	num(b, "ratelimit", c.RateLimit)
	if f := strings.TrimSuffix(c.SampleFreq, "%"); f != "" {
		b.set("sample_freq", f)
	}
	num(b, "max_waiting", c.MaxWaiting)
	num(b, "max_ack_pending", c.MaxAckPending)
	b.flag("headers_only", c.HeadersOnly)
	num(b, "max_batch", c.MaxBatch)
	b.seconds("max_expires", c.MaxExpires)
	num(b, "max_bytes", c.MaxBytes)
	b.seconds("inactive_threshold", c.InactiveThreshold)
	num(b, "replicas", c.Replicas)
	b.flag("memory", c.MemoryStorage)
	b.str("priority_policy", c.PriorityPolicy)
	b.seconds("priority_timeout", c.PriorityTimeout)
	b.list("priority_groups", c.PriorityGroups)
	b.str("delivery_subject", c.DeliverSubject)
	b.str("delivery_group", c.DeliverGroup)
	b.flag("flow_control", c.FlowControl)
	b.seconds("heartbeat", c.IdleHeartbeat)
	b.metadata(c.Metadata)
	return b
}

func bucketBlock(name string, k spec.KVBucket) *block {
	b := &block{header: fmt.Sprintf(`resource "jetstream_kv_bucket" %q`, tfName(name))}
	b.str("name", name)
	b.str("description", k.Description)
	num(b, "history", k.History)
	b.seconds("ttl", k.TTL)
	num(b, "max_value_size", k.MaxValueSize)
	num(b, "max_bucket_size", k.MaxBytes)
	b.str("storage", k.Storage)
	num(b, "replicas", k.Replicas)
	b.seconds("limit_marker_ttl", k.LimitMarkerTTL)
	if p := k.Placement; p != nil {
		b.str("placement_cluster", p.Cluster)
		b.list("placement_tags", p.Tags)
	}
	return b
}
