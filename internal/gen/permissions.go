// permissions is what one service may do on NATS.
type permissions struct {
	publish   []string
	subscribe []string
	responses bool // may reply to requests it received
}

// inbox is where replies arrive. The nats.go default is shared by every client,
// so a service can see replies meant for another one that it can guess the
// subject of. Restrict it per service with nats.CustomInboxPrefix if that matters.
const inbox = "_INBOX.>"

// servicePermissions lists what a service's generated code needs. Each entry is
// proven by a test against a real server, in examples/shop/permissions_test.go.
// Nothing here can create, change or delete a stream, a durable consumer or a
// bucket, so a server using these enforces that applications never change
// infrastructure.
func servicePermissions(s *spec.Spec, service string) permissions {
	sc, err := newScope(s, service)
	if err != nil {
		return permissions{}
	}
	pub, sub := map[string]bool{}, map[string]bool{}
	streams := sc.streams(s)
	for st := range streams {
		pub["$JS.API.STREAM.INFO."+st] = true
	}
	for _, e := range sc.publishes {
		pub[s.EventFilter(e)] = true
	}
	for _, name := range sc.schedules {
		// Recurring schedules use the subject and delayed messages add a token to it.
		subject := s.Schedules[name].Subject
		pub[subject], pub[subject+".*"] = true, true
	}
	for _, e := range sc.subscribes {
		sub[s.EventFilter(e)] = true
	}
	for _, c := range sc.consumers {
		consumerPermissions(s, c, pub, sub)
	}
	for bucket, access := range sc.buckets {
		bucketPermissions(bucket, access, pub)
	}
	for group, endpoints := range sc.clients {
		for _, ep := range endpoints {
			pub[s.Requests[group].Endpoints[ep].Subject] = true
		}
	}
	for _, group := range sc.servers {
		for _, e := range s.Requests[group].Endpoints {
			sub[e.Subject] = true
		}
		// Discovery: $SRV.PING, $SRV.PING.name and $SRV.PING.name.id, and the same for INFO and STATS.
		sub["$SRV.*"], sub["$SRV.*."+group], sub["$SRV.*."+group+".*"] = true, true, true
	}
	if len(streams)+len(sc.buckets)+len(sc.clients) > 0 {
		sub[inbox] = true
	}
	return permissions{publish: spec.SortedKeys(pub), subscribe: spec.SortedKeys(sub), responses: len(sc.servers) > 0}
}

func consumerPermissions(s *spec.Spec, name string, pub, sub map[string]bool) {
	c := s.Consumers[name]
	pub["$JS.API.CONSUMER.INFO."+c.Stream+"."+name] = true
	pub["$JS.ACK."+c.Stream+"."+name+".>"] = true
	if c.DeliverSubject == "" {
		pub["$JS.API.CONSUMER.MSG.NEXT."+c.Stream+"."+name] = true
		return
	}
	sub[c.DeliverSubject] = true
	if c.FlowControl {
		pub["$JS.FC."+c.Stream+".>"] = true
	}
}

// bucketPermissions lets a service read a bucket and watch it. A watch is an
// ephemeral ordered consumer with flow control, so that part of the consumer API
// stays open on the bucket's own stream. Deleting a bucket goes through the stream
// API, which stays closed.
func bucketPermissions(bucket, access string, pub map[string]bool) {
	stream := "KV_" + bucket
	pub["$JS.API.STREAM.INFO."+stream] = true
	pub["$JS.API.STREAM.MSG.GET."+stream] = true
	pub["$JS.API.DIRECT.GET."+stream+".>"] = true
	pub["$JS.API.CONSUMER.CREATE."+stream+".>"] = true
	pub["$JS.API.CONSUMER.DELETE."+stream+".>"] = true
	pub["$JS.FC."+stream+".>"] = true
	if access != "read" {
		pub["$KV."+bucket+".>"] = true
	}
}

var confVariable = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)

func permissionsVariable(service string) string {
	return strings.ToUpper(tfName(service)) + "_PERMISSIONS"
}

// Permissions generates a server config file with each service's permissions as
// a variable. It holds no users or credentials: those stay in the server config
// that includes it.
func Permissions(s *spec.Spec) (map[string][]byte, error) {
	if len(s.Services) == 0 {
		return nil, errors.New("the spec has no services, so there are no permissions to generate")
	}
	var b strings.Builder
	b.WriteString(`# Code generated by gonuts. DO NOT EDIT.
#
# What each service may do on NATS. Include this from a server config, which is
# where users and credentials belong:
#
#   include "permissions.conf"
#   authorization {
#     users: [
#       { user: billing, password: $BILLING_PASSWORD, permissions: $BILLING_PERMISSIONS }
#     ]
#   }
`)
	seen := map[string]string{}
	for _, name := range spec.SortedKeys(s.Services) {
		variable := permissionsVariable(name)
		if !confVariable.MatchString(variable) {
			return nil, fmt.Errorf("service %q does not make a config variable name", name)
		}
		if other, ok := seen[variable]; ok {
			return nil, fmt.Errorf("services %q and %q both make the config variable %s", other, name, variable)
		}
		seen[variable] = name
		writePermissions(&b, variable, servicePermissions(s, name))
	}
	return map[string][]byte{"permissions.conf": []byte(b.String())}, nil
}

func writePermissions(b *strings.Builder, variable string, p permissions) {
	fmt.Fprintf(b, "\n%s = {\n", variable)
	writeDirection(b, "publish", p.publish)
	writeDirection(b, "subscribe", p.subscribe)
	if p.responses {
		b.WriteString("  allow_responses: true\n")
	}
	b.WriteString("}\n")
}

// writeDirection renders one direction. NATS allows everything in a direction
// with no allow list, so an empty one has to deny.
func writeDirection(b *strings.Builder, name string, subjects []string) {
	if len(subjects) == 0 {
		fmt.Fprintf(b, "  %s: { deny: [\">\"] }\n", name)
		return
	}
	fmt.Fprintf(b, "  %s: {\n    allow: [\n", name)
	for _, subject := range subjects {
		fmt.Fprintf(b, "      %s\n", strconv.Quote(subject))
	}
	b.WriteString("    ]\n  }\n")
}
