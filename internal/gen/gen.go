// Package gen turns a spec into Go code and Terraform.
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/jnszkr/gonuts/internal/spec"
)

// Components says which parts of the Go code to generate.
type Components struct {
	Models    bool
	PubSub    bool
	Consumers bool
	KV        bool
	Schedules bool
	RRClient  bool
	RRServer  bool
}

// DefaultComponents is what a run with no flags generates: all the Go code.
func DefaultComponents() Components {
	return Components{Models: true, PubSub: true, Consumers: true, KV: true, Schedules: true, RRClient: true, RRServer: true}
}

// Options configures Go generation.
type Options struct {
	Components Components
	Service    string // generate only what this service uses
	ImportPath string // import path of the output directory
}

// Go generates code, returning file contents keyed by path relative to the output.
func Go(s *spec.Spec, opts Options) (map[string][]byte, error) {
	sc, err := newScope(s, opts.Service)
	if err != nil {
		return nil, err
	}
	g := &generator{s: s, sc: sc, opts: opts, c: opts.Components, files: map[string][]byte{}}
	if g.c.PubSub {
		g.c.PubSub = len(sc.publishes)+len(sc.subscribes) > 0
	}
	if g.c.Consumers {
		g.c.Consumers = len(sc.consumers) > 0
	}
	if g.c.KV {
		g.c.KV = len(sc.buckets) > 0
	}
	if g.c.Schedules {
		g.c.Schedules = len(sc.schedules) > 0
	}
	if g.c.RRClient {
		g.c.RRClient = len(sc.clients) > 0
	}
	if g.c.RRServer {
		g.c.RRServer = len(sc.servers) > 0
	}
	for _, step := range []func() error{g.models, g.events, g.consumers, g.kv, g.schedules, g.clients, g.servers, g.app} {
		if err := step(); err != nil {
			return nil, err
		}
	}
	return g.files, nil
}

type generator struct {
	s     *spec.Spec
	sc    *scope
	opts  Options
	c     Components
	files map[string][]byte
}

func (g *generator) modelsImport() string {
	return strconv.Quote(g.opts.ImportPath + "/models")
}

// write formats a file and stores it. imports are already-quoted import specs.
func (g *generator) write(path, pkg string, imports []string, body string) error {
	var b bytes.Buffer
	b.WriteString("// Code generated by gonuts. DO NOT EDIT.\n\npackage " + pkg + "\n\n")
	if len(imports) > 0 {
		slices.Sort(imports)
		b.WriteString("import (\n" + strings.Join(imports, "\n") + "\n)\n\n")
	}
	b.WriteString(body)
	out, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w\n%s", path, err, b.String())
	}
	g.files[path] = out
	return nil
}

// GoName converts a YAML name into an exported Go identifier.
func GoName(s string) string { return spec.GoName(s) }

// reservedParams are names generated functions already use: their arguments,
// the receivers e and b, and the nuts package that their bodies call.
var reservedParams = map[string]bool{
	"ctx": true, "v": true, "h": true, "opts": true, "subject": true, "err": true, "revision": true, "fn": true, "at": true,
	"e": true, "b": true, "nuts": true,
}

// paramName converts a YAML name into an unexported Go parameter name.
func paramName(s string) string {
	parts := spec.SplitName(s)
	name := strings.ToLower(parts[0])
	for _, p := range parts[1:] {
		name += GoName(p)
	}
	if token.IsKeyword(name) || reservedParams[name] {
		name += "_"
	}
	return name
}

func packageName(s string) string { return spec.PackageName(s) }

var goTypes = map[string]string{"uuid": "string", "time": "time.Time", "duration": "time.Duration", "bytes": "[]byte"}

func goType(t string) string {
	if rest, ok := strings.CutPrefix(t, "[]"); ok {
		return "[]" + goType(rest)
	}
	if rest, ok := strings.CutPrefix(t, "map[string]"); ok {
		return "map[string]" + goType(rest)
	}
	if mapped, ok := goTypes[t]; ok {
		return mapped
	}
	return t
}

func goDuration(d time.Duration) string {
	for _, u := range []struct {
		d    time.Duration
		name string
	}{{time.Hour, "Hour"}, {time.Minute, "Minute"}, {time.Second, "Second"}, {time.Millisecond, "Millisecond"}} {
		if d%u.d == 0 {
			return fmt.Sprintf("%d * time.%s", d/u.d, u.name)
		}
	}
	return fmt.Sprintf("%d", int64(d))
}

func goString(s string) string {
	if strconv.CanBackquote(s) || (!strings.Contains(s, "`") && !strings.ContainsAny(s, "\x00\r")) {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

func comment(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// subjectInfo describes how to build and read one subject template.
type subjectInfo struct {
	format string   // the subject with %s for each parameter
	params []string // YAML parameter names
	tokens []int    // token position of each parameter
	filter string   // the subject with * for each parameter
}

func parseSubject(raw string) (subjectInfo, error) {
	sub, err := spec.ParseSubject(raw)
	if err != nil {
		return subjectInfo{}, fmt.Errorf("subject %q: %w", raw, err)
	}
	out := subjectInfo{params: sub.Params(), tokens: sub.ParamTokens(), filter: sub.Wildcard()}
	tokens := slices.Clone(sub.Tokens())
	for _, i := range out.tokens {
		tokens[i] = "%s"
	}
	out.format = strings.Join(tokens, ".")
	return out, nil
}

// argList renders parameters as a Go signature fragment: "region string, ".
func (si subjectInfo) argList() string {
	var b strings.Builder
	for _, p := range si.params {
		b.WriteString(paramName(p) + " string, ")
	}
	return b.String()
}

// build renders code that puts the final subject in a variable, or returns a
// constant expression when there are no parameters.
func (si subjectInfo) build(onErr string) (setup, expr string) {
	if len(si.params) == 0 {
		return "", strconv.Quote(si.format)
	}
	args := make([]string, len(si.params))
	for i, p := range si.params {
		args[i] = paramName(p)
	}
	setup = fmt.Sprintf("subject, err := nuts.FormatSubject(%q, %s)\nif err != nil {\n%s\n}\n", si.format, strings.Join(args, ", "), onErr)
	return setup, "subject"
}

// writeParams renders an event's parameter struct, its parser and its message alias.
func writeParams(b *strings.Builder, g *generator, event string) error {
	e := g.s.Events[event]
	si, err := parseSubject(e.Subject)
	if err != nil {
		return err
	}
	name := GoName(event)
	fmt.Fprintf(b, "// %sParams holds the variable parts of the %s subject.\ntype %sParams struct {\n", name, event, name)
	for _, p := range si.params {
		fmt.Fprintf(b, "%s string\n", GoName(p))
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "// %sParamsFrom reads the parameters from subject tokens.\nfunc %sParamsFrom(tokens []string) %sParams {\n", name, name, name)
	if len(si.params) == 0 {
		fmt.Fprintf(b, "_ = tokens\nreturn %sParams{}\n}\n\n", name)
	} else {
		fmt.Fprintf(b, "return %sParams{", name)
		for i, p := range si.params {
			fmt.Fprintf(b, "%s: tokens[%d],", GoName(p), si.tokens[i])
		}
		b.WriteString("}\n}\n\n")
	}
	fmt.Fprintf(b, "// %sMsg is a received %s event.\ntype %sMsg = nuts.Msg[models.%s, %sParams]\n\n", name, event, name, e.Model, name)
	return nil
}
