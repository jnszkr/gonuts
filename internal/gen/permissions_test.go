func TestPermissionsGrantOnlyWhatEachServiceDeclares(t *testing.T) {
	cases := map[string]permissions{
		"billing": {
			publish: []string{
				"$JS.ACK.ORDERS.billing-orders.>",
				"$JS.API.CONSUMER.INFO.ORDERS.billing-orders",
				"$JS.API.CONSUMER.MSG.NEXT.ORDERS.billing-orders",
				"$JS.API.STREAM.INFO.ORDERS",
				"orders.shipped.*",
			},
			subscribe: []string{"_INBOX.>"},
		},
		"orders-api": {
			subscribe: []string{"$SRV.*", "$SRV.*.orders", "$SRV.*.orders.*", "orders.api.get"},
			responses: true,
		},
	}
	for name, want := range cases {
		t.Run(name, func(t *testing.T) {
			got := servicePermissions(shop(t), name)
			if !slices.Equal(got.publish, want.publish) {
				t.Errorf("publish = %q, want %q", got.publish, want.publish)
			}
			if !slices.Equal(got.subscribe, want.subscribe) {
				t.Errorf("subscribe = %q, want %q", got.subscribe, want.subscribe)
			}
			if got.responses != want.responses {
				t.Errorf("responses = %v", got.responses)
			}
		})
	}
}

func TestPermissionsSeparateReadFromWriteOnBuckets(t *testing.T) {
	s := shop(t)
	const write = "$KV.carts.>"
	if got := servicePermissions(s, "cart-sweeper").publish; slices.Contains(got, write) {
		t.Errorf("read access can write: %q", got)
	}
	if got := servicePermissions(s, "checkout").publish; !slices.Contains(got, write) {
		t.Errorf("readwrite access cannot write: %q", got)
	}
}

func TestPermissionsCoverPushConsumers(t *testing.T) {
	s := shop(t)
	s.Consumers["pushed"] = spec.Consumer{Stream: "ORDERS", DeliverSubject: "deliver.here", FlowControl: true}
	s.Services["pusher"] = spec.Service{Consumes: []string{"pushed"}}
	got := servicePermissions(s, "pusher")
	if !slices.Contains(got.subscribe, "deliver.here") {
		t.Errorf("subscribe = %q", got.subscribe)
	}
	if !slices.Contains(got.publish, "$JS.ACK.ORDERS.pushed.>") || !slices.Contains(got.publish, "$JS.FC.ORDERS.>") {
		t.Errorf("publish = %q", got.publish)
	}
	if slices.Contains(got.publish, "$JS.API.CONSUMER.MSG.NEXT.ORDERS.pushed") {
		t.Errorf("push consumers do not pull: %q", got.publish)
	}
}

func TestPermissionsCoreEventsNeedNoInbox(t *testing.T) {
	s := shop(t)
	s.Services["pricer"] = spec.Service{Publishes: []string{"price.changed"}, Subscribes: []string{"price.changed"}}
	got := servicePermissions(s, "pricer")
	if !slices.Equal(got.publish, []string{"prices.changed.*"}) || !slices.Equal(got.subscribe, []string{"prices.changed.*"}) {
		t.Fatalf("got %+v", got)
	}
}

func permissionsText(t *testing.T, s *spec.Spec) string {
	t.Helper()
	files, err := Permissions(s)
	if err != nil {
		t.Fatal(err)
	}
	return string(files["permissions.conf"])
}

// A direction with no allow list would be open to everything, so it must deny.
func TestPermissionsDenyADirectionWithNothingToAllow(t *testing.T) {
	s := shop(t)
	s.Services = map[string]spec.Service{"idle": {}}
	mustContain(t, permissionsText(t, s), "IDLE_PERMISSIONS = {", `publish: { deny: [">"] }`, `subscribe: { deny: [">"] }`)
}

func TestPermissionsFileShape(t *testing.T) {
	text := permissionsText(t, shop(t))
	mustContain(t, text, "# Code generated by gonuts. DO NOT EDIT.", "ORDERS_API_PERMISSIONS = {", "allow_responses: true", `"$JS.API.STREAM.INFO.ORDERS"`)
	mustNotContain(t, text, "password =", "token =")
}

func TestPermissionsStopOnNamesWithoutAVariable(t *testing.T) {
	cases := map[string]map[string]spec.Service{
		"no services": {},
		"same":        {"a-b": {}, "a_b": {}},
		"a b":         {"a b": {}},
		"1a":          {"1a": {}},
	}
	for name, services := range cases {
		t.Run(name, func(t *testing.T) {
			s := shop(t)
			s.Services = services
			if _, err := Permissions(s); err == nil {
				t.Fatal("no error")
			}
		})
	}
}

func TestPermissionsOutputIsDeterministic(t *testing.T) {
	first := permissionsText(t, shop(t))
	for range 10 {
		if got := permissionsText(t, shop(t)); got != first {
			t.Fatal("output differs between runs")
		}
	}
	if strings.Count(first, "_PERMISSIONS = {") != 4 {
		t.Fatalf("services in output:\n%s", first)
	}
}

func TestPermissionsGiveAnInboxToAnythingThatWaitsForAReply(t *testing.T) {
	cases := map[string]spec.Service{
		"stream": {Publishes: []string{"order.placed"}},
		"bucket": {KV: map[string]string{"carts": "read"}},
		"client": {Calls: []string{"orders.Get"}},
	}
	for name, service := range cases {
		t.Run(name, func(t *testing.T) {
			s := shop(t)
			s.Services[name] = service
			if got := servicePermissions(s, name).subscribe; !slices.Equal(got, []string{inbox}) {
				t.Fatalf("subscribe = %q", got)
			}
		})
	}
}
